# Embeds shader sources as C++ string literals:
#     embed_shaders.sh <out.h> <namespace> <sources...>
# stage_b.glsl becomes k<namespace's>::kStageBGlsl.
out=$1
namespace=$2
shift 2
{
    echo "// Generated by tools/embed_shaders.sh. Do not edit."
    echo "#pragma once"
    echo "namespace ${namespace} {"
    for f in "$@"; do
        name=${f##*/}
        symbol=""
        IFS='._' read -ra parts <<<"$name"
        for part in "${parts[@]}"; do symbol+="${part^}"; done
        printf 'inline constexpr char k%s[] = R"FFX(' "$symbol"
        cat "$f"
        echo ')FFX";'
    done
    echo "}  // namespace ${namespace}"
} > "$out"
